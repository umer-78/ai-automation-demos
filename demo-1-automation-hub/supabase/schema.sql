-- Northwind Digital Automation Hub: Supabase (Postgres) schema.
-- Paste into the Supabase SQL editor and run. Safe to re-run.
-- The API also creates missing tables on start-up; this file adds the CHECK constraints,
-- row level security and the storage bucket.

create table if not exists public.clients (
  id                 bigint generated by default as identity primary key,
  name               varchar(200) not null unique,
  website            varchar(500),
  industry           varchar(120),
  services           jsonb not null default '[]'::jsonb,
  manager            varchar(120),
  manager_email      varchar(200),
  status             varchar(30) not null default 'new'
                     check (status in ('new', 'onboarding', 'active', 'churned', 'archived')),
  brief              text,
  brief_data         jsonb,
  monthly_budget     double precision,
  airtable_record_id varchar(40) unique,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  archived_at        timestamptz
);

create table if not exists public.client_tasks (
  id         bigint generated by default as identity primary key,
  client_id  bigint not null references public.clients (id) on delete cascade,
  service    varchar(40) not null,
  title      varchar(300) not null,
  position   integer not null default 0,
  status     varchar(20) not null default 'open' check (status in ('open', 'done', 'closed')),
  due_date   date,
  created_at timestamptz not null default now(),
  closed_at  timestamptz,
  constraint uq_task_client_service_title unique (client_id, service, title)
);

create table if not exists public.campaign_metrics (
  id          bigint generated by default as identity primary key,
  client_id   bigint not null references public.clients (id) on delete cascade,
  date        date not null,
  channel     varchar(40) not null,
  impressions integer not null default 0 check (impressions >= 0),
  clicks      integer not null default 0 check (clicks >= 0),
  spend       double precision not null default 0 check (spend >= 0),
  conversions integer not null default 0 check (conversions >= 0),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- the daily job upserts on this key, so re-running it never creates duplicates
  constraint uq_metrics_client_date_channel unique (client_id, date, channel)
);
create index if not exists ix_metrics_date on public.campaign_metrics (date);

create table if not exists public.automation_log (
  id          bigint generated by default as identity primary key,
  run_id      varchar(40) not null,
  workflow    varchar(80) not null,
  status      varchar(20) not null check (status in ('success', 'failure')),
  source      varchar(30) not null default 'python',
  error       text,
  details     jsonb,
  duration_ms integer,
  client_id   bigint,
  created_at  timestamptz not null default now()
);
create index if not exists ix_automation_log_created on public.automation_log (created_at);
create index if not exists ix_automation_log_run on public.automation_log (run_id);

create table if not exists public.site_drafts (
  id              bigint generated by default as identity primary key,
  group_id        varchar(40) not null,
  client_id       bigint references public.clients (id) on delete set null,
  business_name   varchar(200) not null,
  inputs          jsonb not null,
  sections        jsonb not null,
  html            text not null,
  html_url        varchar(600) not null,
  storage_path    varchar(300) not null,
  version         integer not null,
  changed_section varchar(40),
  generated_by    varchar(30) not null,
  created_at      timestamptz not null default now(),
  constraint uq_site_draft_version unique (group_id, version)
);

create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  channel    varchar(20) not null,
  kind       varchar(40) not null default 'message',
  recipient  varchar(200),
  subject    varchar(300),
  body       text not null,
  status     varchar(20) not null,
  error      text,
  run_id     varchar(40),
  created_at timestamptz not null default now()
);
create index if not exists ix_notifications_created on public.notifications (created_at);

create table if not exists public.weekly_summaries (
  id           bigint generated by default as identity primary key,
  run_id       varchar(40) not null,
  client_id    bigint not null references public.clients (id) on delete cascade,
  period_start date not null,
  period_end   date not null,
  sentences    jsonb not null,
  generated_by varchar(30) not null,
  created_at   timestamptz not null default now()
);

create table if not exists public.kv_store (
  key        varchar(120) primary key,
  value      jsonb,
  updated_at timestamptz not null default now()
);

-- Row level security: the API connects with the database connection string, so it is not
-- affected. With RLS on and no policies, the public anon key cannot read or change anything.
alter table public.clients          enable row level security;
alter table public.client_tasks     enable row level security;
alter table public.campaign_metrics enable row level security;
alter table public.automation_log   enable row level security;
alter table public.site_drafts      enable row level security;
alter table public.notifications    enable row level security;
alter table public.weekly_summaries enable row level security;
alter table public.kv_store         enable row level security;

-- Private bucket for generated website drafts (previews are served by the API).
insert into storage.buckets (id, name, public)
values ('site-drafts', 'site-drafts', false)
on conflict (id) do nothing;
