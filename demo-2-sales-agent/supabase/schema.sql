-- Acme Cloud Security Sales Agent: Supabase (Postgres) schema.
-- Paste into the Supabase SQL editor and run. Safe to re-run.
-- The API also creates missing tables on start-up; this file adds the CHECK constraints,
-- indexes and row level security.

-- Mock CRM ---------------------------------------------------------------------------------
create table if not exists public.accounts (
  id                   bigint generated by default as identity primary key,
  company              varchar(200) not null unique,
  domain               varchar(200),
  industry             varchar(160),
  category             varchar(40),
  size                 integer check (size is null or size > 0),
  region               varchar(40),
  cloud_provider       varchar(40),
  stage                varchar(30) not null check (stage in ('Prospect', 'Discovery', 'Proposal', 'Customer')),
  deal_value           double precision check (deal_value is null or deal_value >= 0),
  arr                  double precision check (arr is null or arr >= 0),
  plan                 varchar(30),
  cloud_accounts_used  integer,
  cloud_accounts_limit integer,
  renewal_date         date,
  stage_entered_at     timestamptz not null,
  last_contact         timestamptz,
  owner                varchar(80) not null,
  contact_name         varchar(120),
  contact_title        varchar(120),
  contact_email        varchar(200),
  notes                text,
  score                integer check (score is null or score between 0 and 100),
  score_reason         text,
  score_parts          jsonb,
  flags                jsonb,
  flag_reasons         jsonb,
  analyzed_at          timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

create table if not exists public.activity (
  id          bigint generated by default as identity primary key,
  account_id  bigint not null references public.accounts (id) on delete cascade,
  kind        varchar(20) not null check (kind in ('email', 'call', 'meeting', 'note')),
  direction   varchar(20) not null check (direction in ('outbound', 'inbound', 'internal')),
  summary     text not null,
  occurred_at timestamptz not null,
  created_at  timestamptz not null default now()
);
create index if not exists ix_activity_account on public.activity (account_id, occurred_at);

-- Agent output -----------------------------------------------------------------------------
create table if not exists public.leads (
  id              bigint generated by default as identity primary key,
  company         varchar(200) not null,
  company_key     varchar(200) not null unique,
  domain          varchar(200),
  industry        varchar(200),
  category        varchar(40),
  size_band       varchar(20),
  region          varchar(40),
  cloud_native    varchar(10),
  source_url      varchar(800) not null check (source_url ~ '^https?://'),
  reason          text not null,
  facts           jsonb not null,
  score           integer not null check (score between 0 and 100),
  score_reason    text not null,
  score_parts     jsonb,
  status          varchar(20) not null default 'new'
                  check (status in ('new', 'drafted', 'approved', 'contacted', 'excluded')),
  excluded_reason text,
  research_source varchar(20),
  first_run_id    varchar(40),
  last_run_id     varchar(40),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists ix_leads_score on public.leads (score);

create table if not exists public.drafts (
  id                bigint generated by default as identity primary key,
  kind              varchar(20) not null check (kind in ('outreach', 'follow_up')),
  lead_id           bigint references public.leads (id) on delete cascade,
  account_id        bigint references public.accounts (id) on delete cascade,
  run_id            varchar(40),
  recipient         varchar(200),
  recipient_name    varchar(120),
  subject           varchar(300) not null,
  body              text not null,
  original_subject  varchar(300) not null,
  original_body     text not null,
  cited_fact        text,
  source_url        varchar(800),
  next_step         text,
  send_date         date,
  status            varchar(20) not null default 'pending'
                    check (status in ('pending', 'approved', 'edited', 'rejected', 'sent')),
  lessons_applied   jsonb,
  previous_draft_id bigint,
  generated_by      varchar(20) not null check (generated_by in ('ai', 'template')),
  word_count        integer,
  reviewer          varchar(80),
  reviewed_at       timestamptz,
  sent_at           timestamptz,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now(),
  -- a first email belongs to a lead and must cite a source; a follow-up belongs to a CRM account
  constraint drafts_owner check (
    (kind = 'outreach' and lead_id is not null and source_url is not null and cited_fact is not null)
    or (kind = 'follow_up' and account_id is not null and next_step is not null and send_date is not null)
  )
);
create index if not exists ix_drafts_status on public.drafts (status);

create table if not exists public.feedback (
  id             bigint generated by default as identity primary key,
  draft_id       bigint not null references public.drafts (id) on delete cascade,
  action         varchar(20) not null check (action in ('approve', 'edit', 'reject', 'mark_sent')),
  reason         text,
  edited_subject varchar(300),
  edited_body    text,
  reviewer       varchar(80),
  created_at     timestamptz not null default now(),
  constraint feedback_reject_reason check (action <> 'reject' or length(trim(reason)) >= 3),
  constraint feedback_edit_body check (action <> 'edit' or edited_body is not null)
);
create index if not exists ix_feedback_created on public.feedback (created_at);

create table if not exists public.agent_runs (
  id                varchar(40) primary key,
  trigger           varchar(20) not null check (trigger in ('manual', 'schedule', 'api')),
  mode              varchar(20) not null check (mode in ('live', 'offline')),
  model             varchar(80),
  research_source   varchar(20),
  status            varchar(30) not null
                    check (status in ('running', 'completed', 'completed_with_fallback', 'failed')),
  outcome           text,
  started_at        timestamptz not null,
  finished_at       timestamptz,
  duration_ms       integer,
  tools_called      jsonb not null default '[]'::jsonb,
  tool_call_count   integer not null default 0,
  tokens            integer not null default 0,
  input_tokens      integer not null default 0,
  output_tokens     integer not null default 0,
  cost_usd          double precision not null default 0,
  turns             integer not null default 0,
  leads_scored      integer not null default 0,
  leads_created     integer not null default 0,
  drafts_created    integer not null default 0,
  followups_created integer not null default 0,
  accounts_flagged  integer not null default 0,
  feedback_ids      jsonb not null default '[]'::jsonb,
  context_feedback  text,
  lessons           jsonb,
  icp_version       integer,
  summary           text,
  error             text
);
create index if not exists ix_agent_runs_started on public.agent_runs (started_at);

create table if not exists public.icp_versions (
  id         bigint generated by default as identity primary key,
  version    integer not null unique,
  author     varchar(20) not null check (author in ('agent', 'rep')),
  summary    text not null,
  criteria   jsonb not null,
  note       text,
  run_id     varchar(40),
  created_at timestamptz not null default now()
);

-- Shared operations tables (same as Demo 1) --------------------------------------------------
create table if not exists public.automation_log (
  id          bigint generated by default as identity primary key,
  run_id      varchar(40) not null,
  workflow    varchar(80) not null,
  status      varchar(20) not null check (status in ('success', 'failure')),
  source      varchar(30) not null default 'python',
  error       text,
  details     jsonb,
  duration_ms integer,
  created_at  timestamptz not null default now()
);
create index if not exists ix_automation_log_created on public.automation_log (created_at);

create table if not exists public.notifications (
  id         bigint generated by default as identity primary key,
  channel    varchar(20) not null check (channel = 'slack'),
  kind       varchar(40) not null default 'message',
  recipient  varchar(200),
  body       text not null,
  status     varchar(20) not null check (status in ('sent', 'simulated', 'failed')),
  error      text,
  run_id     varchar(40),
  created_at timestamptz not null default now()
);
create index if not exists ix_notifications_created on public.notifications (created_at);

create table if not exists public.kv_store (
  key        varchar(120) primary key,
  value      jsonb,
  updated_at timestamptz not null default now()
);

-- Row level security: the API connects with the database connection string, so it is not
-- affected. With RLS on and no policies, the public anon key cannot read or change anything.
alter table public.accounts       enable row level security;
alter table public.activity       enable row level security;
alter table public.leads          enable row level security;
alter table public.drafts         enable row level security;
alter table public.feedback       enable row level security;
alter table public.agent_runs     enable row level security;
alter table public.icp_versions   enable row level security;
alter table public.automation_log enable row level security;
alter table public.notifications  enable row level security;
alter table public.kv_store       enable row level security;
